export const XP_THRESHOLDS = [0, 150, 350, 600, 900, 1300, 1800, 2400, 3000];

export function rankFor(xp, lang) {
  let idx = 0;
  for (let i = 0; i < XP_THRESHOLDS.length; i++) if (xp >= XP_THRESHOLDS[i]) idx = i;
  return { index: idx, name: RANKS[lang][idx] || RANKS.en[idx], next: XP_THRESHOLDS[idx + 1] ?? null };
}
